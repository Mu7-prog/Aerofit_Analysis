"""Marginal and Conditional probabilities"""

#Marginal probability
print(df['Product'].value_counts(normalize = True))

#conditional probability
def p_prod_given_gender(gender, print_marginal=False):
    if gender not in ["Female", "Male"]:
        return "Invalid gender value."

    df1 = pd.crosstab(index=df['Gender'], columns=[df['Product']])
    p_781 = df1.loc[gender, 'KP781'] / df1.loc[gender].sum()
    p_481 = df1.loc[gender, 'KP481'] / df1.loc[gender].sum()
    p_281 = df1.loc[gender, 'KP281'] / df1.loc[gender].sum()

    if print_marginal:
        print(f"P(Male): {df1.loc['Male'].sum() / len(df):.2f}")
        print(f"P(Female): {df1.loc['Female'].sum() / len(df):.2f}\n")

    print(f"P(KP781|{gender}): {p_781:.2f}")
    print(f"P(KP481|{gender}): {p_481:.2f}")
    print(f"P(KP281|{gender}): {p_281:.2f}\n")

p_prod_given_gender('Male', True)
p_prod_given_gender('Female')

